function exportName(slug) {
  // simple-icons exports si<PascalCase>, with a leading digit prefixed by `si`.
  const pascal = slug
    .replace(/(^|[^a-z0-9])([a-z0-9])/g, (_, __, c) => c.toUpperCase())
  return `si${pascal}`
}

const entries = []
const missing = []

for (const brand of BRANDS) {
  const icon = si[exportName(brand.slug)]
  if (!icon) {
    missing.push(brand.slug)
    continue
  }
  const aliases = brand.aliases ?? [icon.title.toLowerCase()]
  entries.push({
    key: brand.slug,
    title: icon.title,
    hex: icon.hex,
    path: icon.path,
    // Normalised the same way names are at match time, longest first so the
    // most specific alias wins ("uber eats" before "uber").
    aliases: [...new Set(aliases.map(a => a.toLowerCase().replace(/[^a-z0-9]+/g, ' ').trim()))]
      .sort((a, b) => b.length - a.length),
  })
}

entries.sort((a, b) => a.key.localeCompare(b.key))

const file = `// Generated by scripts/generate-brand-icons.mjs — do not edit by hand.
// Source: simple-icons (CC0-1.0). Brand marks remain trademarks of their
// owners and are used here only to identify the user's own payments.
export interface BrandIcon {
  key: string
  title: string
  /** Official brand colour, without the leading #. */
  hex: string
  /** Single SVG path, drawn in a 24x24 viewBox. */
  path: string
  /** Normalised match keys, longest first. */
  aliases: string[]
}

export const BRAND_ICONS: readonly BrandIcon[] = ${JSON.stringify(entries, null, 2)}
`

writeFileSync(new URL('../lib/utils/brand-icons.generated.ts', import.meta.url), file)

const bytes = Buffer.byteLength(file)
console.log(`Wrote ${entries.length} brands (${(bytes / 1024).toFixed(1)} KB)`)
if (missing.length) {
  console.warn(`Missing from simple-icons (skipped): ${missing.join(', ')}`)
}
